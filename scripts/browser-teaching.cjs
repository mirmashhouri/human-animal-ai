const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { chromium } = require(process.env.WILDLENS_PLAYWRIGHT_PATH || 'playwright');

(async () => {
  const root = path.resolve(__dirname, '..'), output = path.join(root, '.artifacts');
  const testBase = process.env.WILDLENS_TEACHING_TEST_API;
  if (!testBase || !testBase.endsWith(':5097')) throw new Error('Use an isolated teaching test API on port 5097; the owner dataset must not be modified.');
  const browser = await chromium.launch({ headless: true, ...(process.env.WILDLENS_CHROMIUM ? { executablePath: process.env.WILDLENS_CHROMIUM } : {}) });
  try {
    const context = await browser.newContext({ viewport: { width: 1500, height: 1100 }, acceptDownloads: true });
    const page = await context.newPage(); page.setDefaultTimeout(30000);
    const errors = [], modelRequests = [];
    page.on('pageerror', error => errors.push(error.message));
    await context.route('**/api/teaching/**', async route => {
      const url = new URL(route.request().url());
      const response = await route.fetch({ url: testBase + url.pathname + url.search });
      await route.fulfill({ response });
    });
    await context.route('**/api/wildlens/**', route => { modelRequests.push(route.request().url()); return route.abort(); });
    assert.equal((await context.request.get(testBase + '/api/teaching/cases')).status(), 401);
    assert.equal((await context.request.get(testBase + '/api/teaching/photos/train-group-001-original.jpg')).status(), 401);
    await page.goto('http://localhost:8093/teach', { waitUntil: 'networkidle' });
    await page.getByRole('heading', { name: 'Make this space yours.', exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, 'teaching-password-setup.png') });
    await page.getByLabel('Private studio password', { exact: true }).fill('disposable-browser-test-password');
    await page.getByLabel('Repeat password', { exact: true }).fill('disposable-browser-test-password');
    await page.getByRole('button', { name: 'Create private password', exact: true }).click();
    await page.getByRole('heading', { name: 'Teach your eye.', exact: true }).waitFor();
    await page.getByRole('heading', { name: 'Teach this portrait', exact: true }).waitFor();
    await page.getByRole('button', { name: /viewer-left person horse/ }).click();
    await page.getByText('Rejected animals & optional reasoning', { exact: true }).click();
    const initialCount = (await context.request.get(testBase + '/api/teaching/cases').then(r => r.json())).cases.length;
    const cookies = await context.cookies('http://localhost:5086/api/teaching');
    assert.ok(cookies.some(cookie => cookie.name === 'wildlens_teaching' && cookie.httpOnly && cookie.sameSite === 'Strict'));
    assert.equal((await context.request.post(testBase + '/api/teaching/cases/save', { data: {} })).status(), 403, 'Mutations require the private custom header');
    assert.equal((await context.request.get(testBase + '/api/teaching/cases', { headers: { Origin: 'https://untrusted.example' } })).status(), 403);
    assert.ok(await page.getByRole('button', { name: 'Remove horse', exact: true }).count());
    assert.ok((await page.getByLabel(/^Why these animals/).inputValue()).includes('muscular'));
    await page.screenshot({ path: path.join(output, 'teaching-seeded-desktop.png') });
    await page.getByLabel(/^Why these animals/).fill('Long face\nProminent mouth and teeth\nMuscular build');
    await page.getByLabel('Dataset split', { exact: true }).selectOption('test');
    await page.getByRole('button', { name: 'Save example', exact: true }).click();
    await page.getByText('Saved locally. Your vector index is up to date.', { exact: true }).waitFor();
    let data = await context.request.get(testBase + '/api/teaching/cases').then(r => r.json());
    assert.equal(data.cases.length, initialCount); assert.ok(data.cases.filter(item => item.groupId === 'train-group-001').every(item => item.split === 'test'));
    assert.ok(data.cases.find(item => item.caseId === 'train-group-001-left').feedbackQuote.includes('moth and teeth'), 'Original human feedback is preserved');
    await page.getByText('Set crop with numbers', { exact: true }).click();
    for (const [key, value] of Object.entries({ x: '0', y: '55', width: '55', height: '45' })) await page.getByLabel(`Crop ${key} percent`, { exact: true }).fill(value);
    await page.getByRole('button', { name: 'Use selected crop', exact: true }).click();
    await page.getByRole('img', { name: 'Selected benchmark subject crop', exact: true }).waitFor();
    await page.getByText('Advanced annotations · 0 of 32', { exact: true }).click();
    await page.getByLabel('Feature', { exact: true }).selectOption('mouth_width');
    await page.getByRole('button', { name: 'Add feature', exact: true }).click();
    const trait = page.locator('.teach-trait');
    assert.equal(await trait.getByLabel('Value', { exact: true }).inputValue(), '');
    await trait.getByLabel('Visibility', { exact: true }).selectOption('clear');
    await trait.getByLabel('Value', { exact: true }).fill('35');
    await trait.getByLabel('Importance', { exact: true }).selectOption('4');
    await trait.getByLabel('Rendering instruction', { exact: true }).fill('Preserve the broad mouth curve');
    await page.getByRole('button', { name: 'Save example', exact: true }).click();
    await page.getByText('Saved locally. Your vector index is up to date.', { exact: true }).waitFor();
    await page.reload({ waitUntil: 'networkidle' });
    await page.getByRole('heading', { name: 'Teach this portrait', exact: true }).waitFor();
    await page.getByRole('button', { name: /viewer-left person horse/ }).click();
    data = await context.request.get(testBase + '/api/teaching/cases').then(r => r.json());
    const left = data.cases.find(item => item.caseId === 'train-group-001-left');
    assert.equal(left.reference.personOnly, true); assert.equal(left.reference.originalFile, 'references/train-group-001-original.jpg');
    assert.equal(left.traits[0].importance, 4); assert.equal(left.traits[0].value, 35);
    await page.getByText('Rejected animals & optional reasoning', { exact: true }).click();
    await page.getByLabel(/^Why these animals/).fill('An unsaved draft');
    await page.getByRole('button', { name: /^middle person/ }).click();
    await page.getByRole('alert').filter({ hasText: 'Save or discard' }).waitFor();
    await page.getByRole('button', { name: 'Discard changes', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('textarea[aria-label="Why these animals?"]')?.value === 'Long face\nProminent mouth and teeth\nMuscular build');
    const downloadEvent = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Export feedback', exact: true }).click();
    const downloaded = await downloadEvent; assert.equal(downloaded.suggestedFilename(), 'wildlens-private-feedback.jsonl');
    const records = (await fs.readFile(await downloaded.path(), 'utf8')).trim().split('\n').map(line => JSON.parse(line));
    assert.equal(records.length, initialCount); assert.ok(records.find(item => item.caseId === 'train-group-001-middle').acceptedAnimals.includes('frog'));
    await page.getByRole('button', { name: 'Benchmark', exact: true }).click();
    await page.getByRole('heading', { name: 'Comparison benchmark', exact: true }).waitFor();
    const ids = ['train-group-001-left', 'train-group-001-middle', 'train-group-001-right'];
    async function imported(name, version, animals) {
      await page.getByLabel('Run name', { exact: true }).fill(name);
      await page.getByLabel('Prediction version', { exact: true }).fill(version);
      await page.getByLabel('Predictions JSON', { exact: true }).fill(JSON.stringify(ids.map((caseId, index) => ({ caseId, animals: [animals[index]] }))));
      await page.getByRole('button', { name: 'Save imported run', exact: true }).click();
      await page.getByText('Imported predictions and froze the current labels. No model calls made.', { exact: true }).waitFor();
      return (await context.request.get(testBase + '/api/teaching/runs').then(r => r.json())).find(run => run.name === name);
    }
    const a = await imported('UI test baseline fixture', 'test-a', ['bear', 'deer', 'owl']);
    assert.equal(a.metrics.top1Hits, 1);
    const b = await imported('UI test improved fixture', 'test-b', ['horse', 'frog', 'owl']);
    assert.equal(b.metrics.top1Hits, 3);
    await page.getByLabel('Run A', { exact: true }).selectOption(a.id);
    await page.getByLabel('Run B', { exact: true }).selectOption(b.id);
    await page.getByText('Change: +66.7 percentage points', { exact: true }).waitFor();
    await page.getByText('Compare two versions', { exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, 'teaching-benchmark-comparison.png') });
    await page.getByRole('button', { name: 'Teach', exact: true }).click();
    await page.getByLabel('Add teaching photo', { exact: true }).setInputFiles(path.join(root, 'apps/mobile/assets/photos/sample-portrait.jpg'));
    await page.getByRole('heading', { name: 'New portrait', exact: true }).waitFor();
    await page.getByLabel('Person / position', { exact: true }).fill('UI-only portrait');
    await page.getByRole('region', { name: 'Accepted animals', exact: true }).getByRole('button', { name: /^Fox/ }).click();
    await page.getByLabel('This reference shows only this person', { exact: true }).check();
    await page.getByRole('button', { name: 'Save example', exact: true }).click();
    await page.getByText('Saved locally. Your vector index is up to date.', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Archive example', exact: true }).click();
    await page.getByRole('button', { name: 'Restore example', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Restore example', exact: true }).click();
    await page.getByRole('button', { name: 'Archive example', exact: true }).waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('heading', { name: 'Teach your eye.', exact: true }).scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 2), false);
    await page.screenshot({ path: path.join(output, 'teaching-mobile.png') });
    await page.getByRole('button', { name: 'Sign out', exact: true }).click();
    await page.getByRole('heading', { name: 'Welcome back.', exact: true }).waitFor();
    assert.equal((await context.request.get(testBase + '/api/teaching/cases')).status(), 401);
    assert.deepEqual(modelRequests, []); assert.deepEqual(errors, []);
    console.log(JSON.stringify({ status: 'passed', passwordProtection: true, privatePhotos: true, seedExamples: 3,
      subjectCrop: true, persistedFeedback: true, groupedSplits: true, traitAnnotations: true,
      export: true, runComparison: true, uploadArchiveRestore: true, mobile: true, modelCalls: 0, pageErrors: errors }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
