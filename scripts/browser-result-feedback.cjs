const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { chromium } = require(process.env.WILDLENS_PLAYWRIGHT_PATH || 'playwright');

(async () => {
  const base = process.env.WILDLENS_TEACHING_TEST_API;
  if (base !== 'http://localhost:5097') throw new Error('Use the disposable Feedback.Tests fixture, never the owner API.');
  const root = path.resolve(__dirname, '..'), output = path.join(root, '.artifacts');
  await fs.mkdir(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath: process.env.WILDLENS_CHROMIUM });
  try {
    const context = await browser.newContext({ viewport: { width: 1500, height: 1100 }, acceptDownloads: true });
    await context.route('**/api/teaching/**', async route => {
      const url = new URL(route.request().url());
      const response = await route.fetch({ url: base + url.pathname + url.search }); await route.fulfill({ response });
    });
    const page = await context.newPage(), errors = [];
    page.on('pageerror', e => errors.push(e.message));
    assert.equal((await context.request.get(base + '/api/teaching/feedback')).status(), 401);
    await page.goto('http://localhost:8093/teach', { waitUntil: 'networkidle' });
    await page.getByLabel('Private studio password', { exact: true }).fill('disposable-result-feedback-password');
    await page.getByLabel('Repeat password', { exact: true }).fill('disposable-result-feedback-password');
    await page.getByRole('button', { name: 'Create private password', exact: true }).click();
    await page.getByRole('heading', { name: 'Agree or correct.', exact: true }).waitFor();
    await page.locator('.teach-feedback-studio .teach-example').nth(1).waitFor();
    const cases = async () => (await (await context.request.get(base + '/api/teaching/cases')).json()).cases;
    const fixture = async () => (await (await context.request.get(base + '/fixture/status')).json());
    assert.equal((await fixture()).modelRequests, 0, 'Opening the queue does not spend credits');
    assert.equal(await page.locator('.teach-feedback-studio .teach-example').count(), 2);
    await page.getByRole('button', { name: 'Generate my animal', exact: true }).click();
    const result = page.getByRole('img', { name: 'Generated feedback animal portrait', exact: true });
    await result.waitFor(); await result.evaluate(img => img.decode());
    assert.equal((await fixture()).modelRequests, 3);
    assert.equal((await cases()).filter(c => c.feedback).length, 0, 'Generation alone cannot label a case');
    await page.getByRole('radio', { name: 'Disagree', exact: true }).check();
    const save = page.getByRole('button', { name: 'Save feedback & next →', exact: true });
    assert.equal(await save.isDisabled(), true);
    await page.getByLabel('Feedback explanation', { exact: true }).fill('Long face and visible teeth');
    assert.equal(await save.isDisabled(), true, 'Disagree also needs a preferred animal');
    await page.getByLabel('Preferred feedback animal', { exact: true }).fill('Horse');
    await page.getByRole('button', { name: 'Skip →', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'Save or discard' }).waitFor();
    await page.getByRole('button', { name: 'Dismiss error', exact: true }).click();
    await page.screenshot({ path: path.join(output, 'result-feedback-desktop.png'), fullPage: true });
    let response = page.waitForResponse(r => r.url().endsWith('/feedback/review') && r.request().method() === 'POST');
    await save.click(); assert.equal((await response).status(), 200);
    await page.getByRole('status').filter({ hasText: 'Saved. Future new portraits' }).waitFor();
    assert.equal(await page.locator('.teach-feedback-studio .teach-example').count(), 1);
    let stored = await cases(); const corrected = stored.find(c => c.feedback?.verdict === 'disagree');
    assert.equal(corrected.feedback.preferredAnimal, 'Horse'); assert.deepEqual(corrected.rejectedAnimals, ['Bear']);
    assert.equal((await (await context.request.get(base + '/api/teaching/memory')).json()).indexedExamples, 2);
    await page.getByRole('button', { name: 'Generate my animal', exact: true }).click();
    await page.getByRole('radio', { name: 'Agree', exact: true }).waitFor();
    assert.equal((await fixture()).correctionIncluded, true, 'Saved correction reaches the next relevant generation');
    await page.getByRole('radio', { name: 'Agree', exact: true }).check();
    assert.equal(await page.getByLabel('Feedback explanation', { exact: true }).inputValue(), '');
    response = page.waitForResponse(r => r.url().endsWith('/feedback/review') && r.request().method() === 'POST');
    await save.click(); assert.equal((await response).status(), 200);
    await page.getByRole('heading', { name: 'No portraits in this queue.', exact: true }).waitFor();
    stored = await cases(); assert.equal(stored.filter(c => c.feedback).length, 2);
    assert.deepEqual(stored.find(c => c.feedback?.verdict === 'agree').selectionCues, []);
    await page.getByLabel('Feedback queue', { exact: true }).selectOption('reviewed');
    assert.equal(await page.locator('.teach-feedback-studio .teach-example').count(), 2);
    const downloadEvent = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Export result history', exact: true }).click();
    const download = await downloadEvent, downloaded = await download.path();
    assert.equal(JSON.parse(await fs.readFile(downloaded, 'utf8')).filter(r => r.verdict).length, 2);
    await page.getByLabel('Feedback queue', { exact: true }).selectOption('pending');
    await page.getByLabel('Upload feedback portrait', { exact: true }).setInputFiles(path.join(root, 'apps/mobile/assets/photos/sample-portrait.jpg'));
    await page.getByRole('status').filter({ hasText: 'Photo saved on this computer' }).waitFor();
    assert.equal((await cases()).length, 4); assert.equal((await fixture()).modelRequests, 6, 'Uploading is local and makes no generation request');
    await page.reload({ waitUntil: 'networkidle' });
    await page.getByRole('heading', { name: 'Agree or correct.', exact: true }).waitFor();
    assert.equal(await page.locator('.teach-feedback-studio .teach-example').count(), 1);
    await page.getByLabel('Feedback queue', { exact: true }).selectOption('reviewed');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('heading', { name: 'Agree or correct.', exact: true }).scrollIntoViewIfNeeded();
    assert.ok(await page.evaluate(() => document.querySelector('.teach-root').scrollWidth <= window.innerWidth + 1));
    await page.screenshot({ path: path.join(output, 'result-feedback-mobile.png'), fullPage: true });
    assert.deepEqual(errors, []); assert.equal((await fixture()).realMetaCalls, 0);
    console.log(JSON.stringify({ status: 'passed', feedbackVerdicts: 2, correctionUsedByNextRequest: true, export: true, upload: true, reloadPersistence: true, mobile: true, browserErrors: 0, realMetaCalls: 0, ownerDatasetChanged: false }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
