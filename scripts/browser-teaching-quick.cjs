const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { chromium } = require(process.env.WILDLENS_PLAYWRIGHT_PATH || 'playwright');

(async () => {
  const root = path.resolve(__dirname,'..'), base = process.env.WILDLENS_TEACHING_TEST_API;
  if (base !== 'http://localhost:5097') throw new Error('Use the isolated fixture API, never the owner dataset.');
  const browser = await chromium.launch({ headless:true, executablePath:process.env.WILDLENS_CHROMIUM });
  const errors = [], modelCalls = [];
  try {
    const context = await browser.newContext({ viewport:{width:1600,height:1100},acceptDownloads:true });
    const page = await context.newPage(); page.setDefaultTimeout(25000);
    page.on('pageerror',e => errors.push(e.message));
    await context.route('**/api/teaching/**',async route => {
      const url = new URL(route.request().url()); const response = await route.fetch({url:base+url.pathname+url.search}); await route.fulfill({response});
    });
    await context.route('**/api/wildlens/**',route => {modelCalls.push(route.request().url()); return route.abort();});
    assert.equal((await context.request.get(base+'/api/teaching/cases')).status(),401);
    await page.goto('http://localhost:8093/teach',{waitUntil:'networkidle'});
    await page.getByLabel('Private studio password',{exact:true}).fill('quick-browser-disposable-password');
    await page.getByLabel('Repeat password',{exact:true}).fill('quick-browser-disposable-password');
    await page.getByRole('button',{name:'Create private password',exact:true}).click();
    await page.getByRole('heading',{name:'Teach your eye.',exact:true}).waitFor();
    const cases = () => context.request.get(base+'/api/teaching/cases').then(r => r.json()).then(r => r.cases);
    const initial = await cases(); assert.equal(initial.length,103); assert.equal(initial.filter(c=>c.starterPack).length,100);
    assert.equal(initial.filter(c=>c.starterPack && c.acceptedAnimals.length).length,0,'No invented starter labels');
    await page.getByRole('heading',{name:'Teach this portrait',exact:true}).waitFor();
    await page.waitForFunction(()=>document.querySelector('input[placeholder="Viewer-left person in a gray shirt"]')?.value==='Tom Hanks');
    assert.equal(await page.getByRole('slider').count(),20);
    assert.equal(await page.getByRole('checkbox',{name:/^Standout /}).count(),20);
    const photo = page.getByRole('img',{name:'Original teaching photo',exact:true});
    await photo.evaluate(img=>img.decode());
    await page.getByText('Photo source & license',{exact:true}).click();
    assert.ok(await page.getByRole('link',{name:'Wikimedia source ↗',exact:true}).getAttribute('href'));
    const picker = page.getByRole('region',{name:'Accepted animals',exact:true});
    await picker.getByRole('searchbox').fill('اسب');
    await picker.getByRole('button',{name:/^Horse/}).click();
    await page.getByLabel('Standout nose_length',{exact:true}).check();
    await page.getByLabel('Standout mouth_width',{exact:true}).check();
    async function rate(key,value) { await page.getByRole('slider',{name:`Rate ${key}`,exact:true}).fill(String(value)); }
    await rate('face_ratio',4); await rate('nose_length',5); await rate('tooth_display',3);
    const tom = initial.find(c=>c.personPosition==='Tom Hanks');
    await page.getByRole('heading',{name:'Teach this portrait',exact:true}).scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(root,'.artifacts/teaching-quick-desktop.png')});
    await page.getByRole('button',{name:'Save & next →',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('input[placeholder="Viewer-left person in a gray shirt"]')?.value==='Viola Davis');
    let stored = (await cases()).find(c=>c.caseId===tom.caseId);
    assert.deepEqual(stored.acceptedAnimals,['Horse']); assert.equal(stored.traitScale,5);
    assert.equal(stored.traits.find(t=>t.key==='nose_length').value,5); assert.equal(stored.traits.some(t=>t.key==='eye_size'),false);
    assert.deepEqual(stored.salientFeatures,['nose_length','mouth_width']);
    await page.reload({waitUntil:'networkidle'});
    await page.waitForFunction(()=>document.querySelector('input[placeholder="Viewer-left person in a gray shirt"]')?.value==='Viola Davis');
    await picker.getByRole('button',{name:/^Fish/}).click(); await picker.getByRole('button',{name:/^Frog/}).click();
    await rate('face_roundness',4); await rate('eye_roundness',4); await page.getByLabel('Standout eye_roundness',{exact:true}).check();
    await page.getByRole('button',{name:'Save & next →',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('input[placeholder="Viewer-left person in a gray shirt"]')?.value==='Denzel Washington');
    await picker.getByRole('button',{name:/^Bear/}).click();
    await page.getByRole('button',{name:'Set midpoint mouth_width',exact:true}).click();
    await page.getByRole('button',{name:'Save example',exact:true}).click();
    await page.getByText('Saved locally. Your vector index is up to date.',{exact:true}).waitFor();
    stored = (await cases()).find(c=>c.personPosition==='Denzel Washington');
    assert.equal(stored.traits.find(t=>t.key==='mouth_width').value,0,'Explicit midpoint is stored separately from missing ratings');
    await picker.getByRole('button',{name:/^Fox/}).click();
    await page.getByRole('button',{name:'Skip →',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'Save or discard'}).waitFor();
    await page.getByRole('button',{name:'Discard changes',exact:true}).click();
    await page.getByRole('button',{name:'Memory · RAG',exact:true}).click();
    await page.getByRole('heading',{name:'Your visual memory',exact:true}).waitFor();
    let memory = await context.request.get(base+'/api/teaching/memory').then(r=>r.json()); assert.equal(memory.indexedExamples,3);
    await page.getByRole('button',{name:'Turn memory off',exact:true}).click();
    await page.getByRole('button',{name:'Turn memory on',exact:true}).waitFor();
    await page.getByRole('button',{name:'Turn memory on',exact:true}).click();
    const downloadPromise = page.waitForEvent('download'); await page.getByRole('button',{name:'Export trait vectors',exact:true}).click();
    const download = await downloadPromise; const vectors = JSON.parse(await fs.readFile(await download.path(),'utf8'));
    assert.equal(vectors.vectors.length,3); assert.equal(vectors.vectors.find(v=>v.caseId===tom.caseId).values.filter(v=>v!==null).length,3);
    await page.screenshot({path:path.join(root,'.artifacts/teaching-memory.png')});
    await page.getByRole('button',{name:'Benchmark',exact:true}).click();
    await page.getByText('Run the current matcher · uses Meta credits',{exact:true}).click();
    await page.getByLabel('Matcher version',{exact:true}).selectOption('memory');
    assert.ok(await page.getByRole('button',{name:'Run current matcher',exact:true}).isDisabled(),'No real model use in fixture API');
    await page.getByRole('button',{name:'Teach',exact:true}).click();
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('heading',{name:'Teach this portrait',exact:true}).scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2),false);
    await page.screenshot({path:path.join(root,'.artifacts/teaching-quick-mobile.png')});
    const feedbackDownload = page.waitForEvent('download'); await page.getByRole('button',{name:'Export feedback',exact:true}).click();
    const feedback = await feedbackDownload; assert.equal((await fs.readFile(await feedback.path(),'utf8')).trim().split('\n').length,103);
    await page.getByRole('button',{name:'Sign out',exact:true}).click();
    await page.getByRole('heading',{name:'Welcome back.',exact:true}).waitFor();
    assert.equal((await context.request.get(base+'/api/teaching/memory/export')).status(),401);
    assert.equal((await context.request.get(base+'/api/teaching/photos/'+tom.reference.file.split('/').pop())).status(),401);
    assert.deepEqual(modelCalls,[]); assert.deepEqual(errors,[]);
    console.log(JSON.stringify({status:'passed',starterPortraits:100,previousCases:3,animalSearch:'Persian + English',sliders:20,standoutCheckboxes:true,saveAndNext:true,resumeAfterReload:true,nullVersusZero:true,localVectorPersistence:true,memoryToggle:true,vectorAndFeedbackExports:true,benchmarkMode:true,mobile:true,realModelCalls:0,pageErrors:errors},null,2));
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
